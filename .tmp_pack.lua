local function check(label, f, ...)
  local ok, err = pcall(f, ...)
  print(label, ok, err)
end
check("i0", string.pack, "i0", 0)
check("i17", string.pack, "i17", 0)
check("align17", string.pack, "Xi17", 0)
check("r", string.pack, "i3r", 0)
check("i16", string.unpack, "i16", string.rep("\3", 16))
check("align4", string.pack, "!4i3", 0)
check("missing", string.pack, "c", "")
check("var", string.packsize, "s")
check("invalid", string.packsize, "c1" .. string.rep("0", 40))
check("next", string.pack, "X")
check("nextspace", string.pack, "X i", 0)
local s = string.rep("c268435456", 8)
local ok, err = pcall(string.packsize, s)
print("repeat", ok, err)
check("2147483648", string.packsize, "c2147483648")
local s2 = string.rep("c268435456", 7) .. "c268435455"
local ok2, err2 = pcall(string.packsize, s2)
print("one-less", ok2, err2)
